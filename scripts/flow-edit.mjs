import { chromium } from 'playwright-core';
import assert from 'node:assert';
const b = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true });
const c = await b.newContext({ viewport: { width: 430, height: 900 } });
const p = await c.newPage();
const errors=[]; p.on('pageerror',e=>errors.push(e.message));
await p.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' });
await p.getByRole('button', { name: /already have an account/i }).click();
await p.getByRole('button', { name: /Student buyer/i }).click();
await p.getByRole('button', { name: /^Sign in$/i }).click();
await p.waitForURL('**/#/home');
await p.goto('http://127.0.0.1:5173/#/sell?edit=l8', { waitUntil: 'networkidle' });
assert((await p.locator('#sell-title').inputValue()).includes('MCL Organization Hoodie'), 'prefilled title');
await p.getByRole('button', { name: /Continue to pricing/i }).click();
await p.getByLabel('Price').fill('575');
await p.getByRole('button', { name: /Continue to photos/i }).click();
await p.locator('input[type=file]').setInputFiles('C:/Users/Kaira/Documents/DEV/ENTREP/campussmart/public/img/coffee.jpg');
await p.getByText(/Photo added to your listing/i).waitFor();
const previewSrc = await p.locator('.preview-card img').getAttribute('src');
assert(previewSrc?.startsWith('data:image/'), 'uploaded image preview');
await p.getByRole('button', { name: /Save changes/i }).click();
await p.waitForTimeout(800);
assert(p.url().includes('/#/product/l8'), 'back on product');
const stored = await p.evaluate(() => { const s=JSON.parse(localStorage.getItem('campussmart.state.v1')); const l=s.listings.find(x=>x.id==='l8'); return {price:l.price, img:l.image.slice(0,22)}; });
assert(stored.price === 575, 'price updated');
assert(stored.img.startsWith('data:image/'), 'image persisted');
console.log('edit and upload works', stored.img);
console.log('errors', errors);
await b.close();
